/** Why an idea suits the brand; fragrance brands get a tailored explanation. */
export function relevance(concept, brand) {
  const text = `${brand.description} ${brand.name}`.toLowerCase();
  if (/عطر|عطور|perfume|fragrance|لوما|luma/.test(text)) return FRAGRANCE_LINKS[concept.id] || concept.why;
  return concept.why;
}

/** Six ideas: the chosen region first, then nationwide ideas, then the rest; `round` rotates each group. */
export function pickIdeas(region, round) {
  const regional = CONCEPTS.filter((c) => region === "all" || c.region === region);
  const general = CONCEPTS.filter((c) => c.region === "all" && !regional.includes(c));
  const others = CONCEPTS.filter((c) => !regional.includes(c) && !general.includes(c));
  const cycle = (list) => (list.length ? [...list.slice(round % list.length), ...list.slice(0, round % list.length)] : []);
  return [...cycle(regional), ...cycle(general), ...cycle(others)].slice(0, 6);
}
